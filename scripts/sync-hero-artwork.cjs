const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const directory = path.join(root, 'public', 'heroes')
function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(item => {
    const full = path.join(dir, item.name)
    return item.isDirectory() ? files(full) : item.name.endsWith('.png') ? [full] : []
  })
}
const names = files(directory).map(file => path.relative(path.join(root, 'public'), file).replaceAll('\\', '/')).sort()
const source = '// Generated by scripts/sync-hero-artwork.cjs; public PNGs are served directly.\nexport const heroArtworkFiles: readonly string[] = '+JSON.stringify(names, null, 2)+'\n'
const target = path.join(root, 'src', 'lib', 'heroArtwork.ts')
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) fs.writeFileSync(target, source)
