export function normalizeIconQuery(query: string) { return query.trim().toLocaleLowerCase('ru-RU').replace(/ё/g, 'е') }

export function searchSkillIcons(query: string) {
  const normalized = normalizeIconQuery(query)
  return skillIcons.filter(item => normalizeIconQuery(`${item.name} ${item.group} ${item.keywords ?? ''}`).includes(normalized))
}

const icons: Record<string, LucideIcon> = Object.fromEntries(skillIcons.map((icon) => [icon.id, icon.component]))
icons['❤️'] = Heart

export function canonicalSkillIcon(icon: string) { return icon === '❤️' ? '❤' : icon }

export function SkillIcon({ icon, size = 16 }: { icon: string; size?: number }) {
  const Icon = icons[icon]
  return Icon ? <Icon size={size} aria-hidden="true" /> : <span aria-hidden="true">{icon}</span>
}
